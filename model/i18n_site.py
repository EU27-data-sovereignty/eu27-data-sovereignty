#!/usr/bin/env python3
"""
The site catalog: every sentence the web app writes itself, in English and in the site languages (#113).

    python3 model/i18n_site.py extract   # rewrite docs/i18n/site/SOURCE.md from the code
    python3 model/i18n_site.py check     # source in step with the code, drafts well formed and cross-reviewed
    python3 model/i18n_site.py stale     # list, per language, the source strings its draft does not cover yet

The English stays in the code, where a reader of a component can see it: `tx('…')` and `txr('…')` translate at
render, and `m('…')` marks a string in a data file (the guides) that a component translates later. This script
reads those calls; nothing else decides what is in the catalog. Each string's id is a hash of its English, so an
edited sentence is a new string: its old translation stops matching, and the page prints the new English until
the drafts catch up. `stale` lists those; `check` fails only on what would print wrongly (a draft whose English
no longer matches its id, a placeholder lost in translation, a cell unreviewed or reviewed by its own drafter).

The 47 strings of docs/i18n/STRINGS.md keep their own drafts and the stricter whole-language admission of #111
and #112; this catalog is the prose around them.
"""
from __future__ import annotations

import hashlib
import json
import re
import sys
import unicodedata
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import i18n_drafts as drafts

ROOT = drafts.ROOT
WEB = ROOT / "web" / "src"
SITE = ROOT / "docs" / "i18n" / "site"
SOURCE = SITE / "SOURCE.md"
OUT = ROOT / "model" / "i18n" / "site"

CALL = re.compile(r"\b(tx|txr|m)\(\s*(['\"`])((?:\\.|(?!\2).)*)\2", re.DOTALL)
ARG = re.compile(r"\{\s*([A-Za-z_]\w*)")


def sid(en: str) -> str:
    return "s." + hashlib.sha1(en.encode("utf-8")).hexdigest()[:10]


def _unescape(raw: str, quote: str) -> str:
    return re.sub(r"\\(.)", lambda m: {"n": "\n", "t": "\t"}.get(m.group(1), m.group(1)), raw)


def extract() -> tuple[dict[str, tuple[str, list[str]]], list[str]]:
    """id -> (English, [files]) for every catalog call in web/src, and the problems found reading them."""
    found: dict[str, tuple[str, list[str]]] = {}
    problems: list[str] = []
    for f in sorted(WEB.rglob("*.ts*")):
        if "__tests__" in f.parts or f.parent.name == "i18n":
            continue
        rel = str(f.relative_to(ROOT))
        for m in CALL.finditer(f.read_text(encoding="utf-8")):
            quote, raw = m.group(2), m.group(3)
            if quote == "`" and "${" in raw:
                problems.append(f"{rel}: {m.group(1)}(`…${{…}}…`) builds a sentence; use an argument: {raw[:60]!r}")
                continue
            en = _unescape(raw, quote)
            if not en.strip() or en != en.strip():
                problems.append(f"{rel}: empty or padded catalog string {en!r}")
                continue
            entry = found.setdefault(sid(en), (en, []))
            if rel not in entry[1]:
                entry[1].append(rel)
    return found, problems


def _cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", "<br>")


def _uncell(text: str) -> str:
    return text.replace("<br>", "\n")


def source_text(found: dict[str, tuple[str, list[str]]]) -> str:
    lines = ["# Site strings: the English source", "",
             "Generated by `python3 model/i18n_site.py extract` from the `tx`, `txr` and `m` calls in `web/src`.",
             "Do not edit: change the English in the code and re-run. Drafts translate this table (#113).", "",
             f"{len(found)} strings.", "", "| key | en | where |", "|---|---|---|"]
    for key, (en, files) in sorted(found.items(), key=lambda kv: (kv[1][1][0], kv[1][0])):
        where = ", ".join(f.removeprefix("web/src/") for f in files)
        lines.append(f"| {key} | {_cell(en)} | {where} |")
    return "\n".join(lines) + "\n"


def source() -> dict[str, str]:
    if not SOURCE.exists():
        return {}
    rows = drafts._rows(SOURCE.read_text(encoding="utf-8").splitlines())[1:]
    return {r[0]: _uncell(r[1]) for r in rows if len(r) >= 2}


def site_langs() -> list[str]:
    return [e["lang"] for e in json.loads((ROOT / "model" / "i18n" / "site.json").read_text(encoding="utf-8"))]


def _blocks(text: str) -> list[str]:
    """The top-level `{…}` blocks of an ICU message, without their braces."""
    out, depth, start = [], 0, 0
    for i, ch in enumerate(text):
        if ch == "{":
            if depth == 0:
                start = i + 1
            depth += 1
        elif ch == "}" and depth:
            depth -= 1
            if depth == 0:
                out.append(text[start:i])
    return out


def plurals_of(text: str) -> list[set[str]]:
    """The category set of every `{x, plural, …}` block in an ICU message, nested ones included."""
    found: list[set[str]] = []
    for block in _blocks(text):
        head, _, rest = block.partition(",")
        kind, _, body = rest.partition(",")
        if kind.strip() != "plural":
            continue
        cats, depth, word = set(), 0, ""
        for ch in body:
            if ch == "{":
                if depth == 0 and word.strip():
                    cats.add(word.strip())
                depth += 1
                word = ""
            elif ch == "}":
                depth -= 1
            elif depth == 0:
                word += ch
        found.append({c for c in cats if not c.startswith("=")})
        for branch in _blocks(body):
            found += plurals_of(branch)
    return found


def args_of(text: str) -> set[str]:
    """The argument names an ICU message uses: `{name}`, and `{n, plural, …}` with the arguments in its branches.
    A branch's own braces hold text, so a one-word branch (`one {value}`) is not mistaken for an argument."""
    names: set[str] = set()
    for block in _blocks(text):
        head, _, rest = block.partition(",")
        if not ARG.fullmatch("{" + head.strip()):
            continue
        names.add(head.strip())
        if "plural" in rest:
            for branch in _blocks(rest):
                names |= args_of(branch)
    return names


def draft(lang: str) -> dict:
    """The draft for `lang`: its cells, review verdicts and header fields."""
    path = SITE / f"{lang}.md"
    if not path.exists():
        return {"exists": False, "cells": {}, "en": {}, "review": {}, "drafted": "", "reviewed": ""}
    text = path.read_text(encoding="utf-8")
    grid = drafts._table_after(text, "Strings")
    cells, en = {}, {}
    for r in grid[1:]:
        if len(r) >= 3:
            en[r[0]], cells[r[0]] = _uncell(r[1]), _uncell(r[2])
    review = {}
    for r in drafts._table_after(text, "Review")[1:]:
        if len(r) >= 3:
            review[r[0]] = (r[2].lower(), r[4] if len(r) > 4 else "")
    return {"exists": True, "text": text, "cells": cells, "en": en, "review": review,
            "drafted": drafts._field(text, "Drafted by"), "reviewed": drafts._field(text, "Reviewed by")}


def check(verbose: bool = True) -> int:
    found, problems = extract()
    src = source()
    if {k: v[0] for k, v in found.items()} != src:
        problems.append("docs/i18n/site/SOURCE.md is not what the code says; run python3 model/i18n_site.py extract")
    ok = fix = stale = 0
    for lang in site_langs():
        d = draft(lang)
        if not d["exists"]:
            stale += len(src)
            continue
        if unicodedata.normalize("NFC", d["text"]) != d["text"]:
            problems.append(f"{lang}: file is not Unicode NFC")
        if d["drafted"].split(",")[0].strip() == d["reviewed"].split(",")[0].strip() and d["reviewed"]:
            problems.append(f"{lang}: reviewed by its own drafter")
        for key, cell in d["cells"].items():
            if key not in src:
                continue  # an old string the code no longer prints; harmless, dropped at the next draft pass
            if d["en"][key] != src[key]:
                problems.append(f"{lang}: {key} English differs from the source")
            if not cell or cell != cell.strip():
                problems.append(f"{lang}: {key} is empty or padded")
            if args_of(cell) != args_of(src[key]):
                problems.append(f"{lang}: {key} placeholders {sorted(args_of(cell))} != {sorted(args_of(src[key]))}")
            if src[key].count("{") != cell.count("{") and "plural" not in src[key]:
                problems.append(f"{lang}: {key} brace count differs from the English")
            want = drafts.PLURALS.get(lang)
            for cats in plurals_of(cell):
                if want is not None and cats != want:
                    problems.append(f"{lang}: {key} plural gives {sorted(cats)}, {lang} has {sorted(want)}")
            if len(plurals_of(cell)) != len(plurals_of(src[key])):
                problems.append(f"{lang}: {key} has {len(plurals_of(cell))} plural blocks, the English has "
                                f"{len(plurals_of(src[key]))}")
            verdict = d["review"].get(key, ("", ""))[0]
            if verdict not in ("ok", "fix"):
                problems.append(f"{lang}: {key} has no review verdict")
            elif verdict == "fix":
                fix += 1
            else:
                ok += 1
        stale += sum(1 for k in src if k not in d["cells"])
    if verbose:
        print(f"{len(src)} site strings, {len(site_langs())} languages, {ok} ok, {fix} fix, "
              f"{stale} not yet drafted, {len(problems)} problems")
        for p in problems:
            print(f"  {p}")
    return 1 if problems else 0


def admitted(lang: str) -> dict[str, str]:
    """English -> translation for every cell of `lang` that is reviewed `ok` and matches the current source."""
    src, d = source(), draft(lang)
    if not d["exists"] or not d["reviewed"]:
        return {}
    out = {}
    for key, cell in d["cells"].items():
        if key in src and d["en"].get(key) == src[key] and d["review"].get(key, ("", ""))[0] == "ok":
            out[src[key]] = cell
    return out


def main(argv: list[str]) -> int:
    cmd = argv[0] if argv else "check"
    if cmd == "extract":
        found, problems = extract()
        SOURCE.parent.mkdir(parents=True, exist_ok=True)
        SOURCE.write_text(source_text(found), encoding="utf-8")
        print(f"wrote docs/i18n/site/SOURCE.md: {len(found)} strings")
        for p in problems:
            print(f"  {p}")
        return 1 if problems else 0
    if cmd == "check":
        return check()
    if cmd == "stale":
        src = source()
        for lang in site_langs():
            missing = [k for k in src if k not in draft(lang)["cells"]]
            print(f"{lang}: {len(missing)} of {len(src)} not drafted")
        return 0
    print(__doc__)
    return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
