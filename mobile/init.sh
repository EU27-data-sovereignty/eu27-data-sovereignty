#!/usr/bin/env bash
# Everything needed to work on the mobile reader. Exit 0 = ready. Idempotent.
#
#   ./init.sh              check Node and npm, npm ci, generate the 28 parts of the edition, create an
#                          .env.local you may leave empty (the app then reads its bundled edition offline)
#   ./init.sh --supabase   also check the Supabase CLI and start the local stack on Colima, which only
#                          ./test.sh --integration needs
set -euo pipefail
cd "$(dirname "$0")"

WITH_SUPABASE=0
for arg in "$@"; do
    case "$arg" in
        --supabase) WITH_SUPABASE=1 ;;
        -h|--help) sed -n '2,7p' "$0" | sed 's/^# \{0,1\}//'; exit 0 ;;
        *) echo "Unknown option: $arg (see ./init.sh --help)"; exit 2 ;;
    esac
done

GREEN='\033[0;32m'; RED='\033[0;31m'; YELLOW='\033[1;33m'; BLUE='\033[0;34m'; RESET='\033[0m'

# React Native 0.86 / Metro require Node ^20.19.4 || ^22.13.0 || ^24.3.0 || >=25; .nvmrc pins 24 to match the root.
check_node_version() {
    local min_version="20.19.4" current_version
    if ! command -v node &> /dev/null; then
        echo -e "${RED}❌ Node.js is not installed (nvm install 24; see .nvmrc)${RESET}"; exit 1
    fi
    current_version=$(node -v | cut -d'v' -f2)
    if [ "$(printf '%s\n' "$min_version" "$current_version" | sort -V | head -n1)" != "$min_version" ]; then
        echo -e "${RED}❌ Node.js $min_version+ is required. Current: v$current_version (try: nvm use)${RESET}"; exit 1
    fi
    echo -e "${GREEN}✅ Node.js v$current_version${RESET}"
    if ! command -v npm &> /dev/null || ! command -v npx &> /dev/null; then
        echo -e "${RED}❌ npm/npx are not available${RESET}"; exit 1
    fi
    echo -e "${GREEN}✅ npm $(npm -v)${RESET}"
}

check_python() {
    if ! command -v python3 &> /dev/null; then
        echo -e "${RED}❌ python3 is required: the parts of the edition are generated by ../model/export_json.py${RESET}"; exit 1
    fi
    echo -e "${GREEN}✅ $(python3 --version)${RESET}"
}

install_deps() {
    # npm ci installs exactly what package-lock.json records — the same tree CI tests. Never delete the
    # lockfile to "refresh" it (the ajv bug the template records); upgrade with targeted installs.
    if [ -d node_modules ] && npm ls --depth=0 > /dev/null 2>&1; then
        echo -e "${GREEN}✅ node_modules already matches package-lock.json${RESET}"
    else
        npm ci --no-fund --no-audit
    fi
}

setup_environment() {
    if [ ! -f .env.local ]; then
        (umask 077 && cp .env.template .env.local) && chmod 600 .env.local
        echo -e "${GREEN}📋 Created .env.local from .env.template (empty: offline, bundled edition only)${RESET}"
    else
        echo -e "${GREEN}✅ .env.local exists${RESET}"
    fi
}

setup_supabase() {
    if ! command -v supabase &> /dev/null; then
        echo -e "${YELLOW}⚠️ Supabase CLI not found: brew install supabase/tap/supabase (2.120.0 is what CI pins)${RESET}"; return 0
    fi
    echo -e "${GREEN}✅ Supabase CLI $(supabase --version)${RESET}"
    if command -v docker &> /dev/null && docker info &> /dev/null; then
        if supabase start; then
            echo -e "${GREEN}✅ Local Supabase is up (Storage at http://127.0.0.1:54321/storage/v1, Studio at http://127.0.0.1:54323)${RESET}"
        else
            echo -e "${YELLOW}⚠️ supabase start failed. Another project's stack may hold the ports: supabase stop --project-id <other>${RESET}"
        fi
    else
        echo -e "${YELLOW}⚠️ No Docker daemon. Start one with: colima start   (then: supabase start)${RESET}"
    fi
}

echo -e "${GREEN}🚀 EU-27 Data Sovereignty — the mobile reader${RESET}"
echo -e "${BLUE}🔍 Checking prerequisites...${RESET}"
check_node_version
check_python
echo -e "${BLUE}📦 Installing dependencies...${RESET}"
install_deps
echo -e "${BLUE}🧩 Generating the split edition...${RESET}"
./run.sh parts
echo -e "${BLUE}⚙️ Setting up environment...${RESET}"
setup_environment
if [ "$WITH_SUPABASE" -eq 1 ]; then
    echo -e "${BLUE}🗃️ Local Supabase (for ./test.sh --integration)...${RESET}"
    setup_supabase
fi

echo -e "${GREEN}✅ Ready.${RESET}"
echo -e "  ${GREEN}./run.sh web${RESET}                   the app in a browser (or ios / android / start)"
echo -e "  ${GREEN}./test.sh${RESET}                      every check; ${GREEN}--quick${RESET} for the developer loop"
echo -e "  ${GREEN}./init.sh --supabase${RESET} then ${GREEN}./test.sh --integration${RESET}   the live round-trip against the local bucket"
